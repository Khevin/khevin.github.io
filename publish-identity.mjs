/* Promotes the Signal exploration to the live site.
 *
 * The exploration was always a CSS layer over the real pages — it never
 * restructured a body, and its build proved that on every run. Publishing is
 * therefore not a merge: it is moving that layer out of explorations/ and
 * linking it from the four pages it was always styling.
 *
 * Idempotent. Run it again after changing the exploration and it re-copies.
 *
 *   node publish-identity.mjs
 *
 * The sources it copies now live in explorations/parked/ — the exploration was
 * retired once this ran. Re-run it only after changing them, or after
 * download-display-fonts.mjs adds a family.
 */
import { readFile, writeFile, copyFile } from 'node:fs/promises';

const PAGES = ['index.html', 'process.html', 'blog.html', 'books.html'];
const nl = (s) => (s.includes('\r\n') ? '\r\n' : '\n');

/* ---- 1. the fonts and their stylesheets already live here ---------------- */
/* explorations/download-*.mjs write straight into fonts/, fonts.css and
   display-fonts.css at this root — there is nothing to copy. */

/* ---- 2. one identity stylesheet ----------------------------------------- */
/* signal-original.css only ever held #clients rules, which are scoped by that
   id and so are inert on the other three pages. Two files were a build-time
   convenience, not a boundary worth keeping. */
const shared = await readFile('explorations/parked/signal.css', 'utf8');
const home = await readFile('explorations/parked/signal-original.css', 'utf8');
const N = nl(shared);

const identity = [
  '/* Signal — the site identity.',
  '   Type, palette, the nav, the ink-inversion row, and the bar section on the',
  '   home page. Loads AFTER styles.css and overrides it; styles.css still owns',
  '   the layout. Generated by publish-identity.mjs from explorations/ — edit it',
  '   there and re-run, or adopt this file and retire the exploration. */',
  '',
  shared.replace(/^\/\*[\s\S]*?\*\/\r?\n/, '').trimStart(),
  '',
  home
    .replace(/^\/\*[\s\S]*?\*\/\r?\n/, '')
    .trimStart()
    // The exploration sat one directory down; this file does not.
    .replaceAll('../assets/', './assets/'),
].join(N);

await writeFile('identity.css', identity, 'utf8');
console.log(`identity.css      ${Math.round(identity.length / 1024)}KB`);

/* ---- 3. the nav's current-page marker ------------------------------------ */
await copyFile('explorations/parked/signal.js', 'nav-current.js');
console.log('nav-current.js    copied');

/* ---- 4. link it from every page ----------------------------------------- */
const HEAD = [
  '<link rel="stylesheet" href="./fonts.css" />',
  '<link rel="stylesheet" href="./display-fonts.css" />',
  '<link rel="stylesheet" href="styles.css" />',
  '<link rel="stylesheet" href="./identity.css" />',
  '<script src="./nav-current.js" defer></script>',
];

for (const page of PAGES) {
  let s = await readFile(page, 'utf8');
  const NP = nl(s);

  if (s.includes('./identity.css')) {
    console.log(`${page.padEnd(18)}already linked`);
  } else {
    const before = s;
    // Drop the Google Fonts CDN: every face is self-hosted now.
    s = s.replace(/[ \t]*<link rel="preconnect"[^>]*>\r?\n/g, '');
    s = s.replace(
      /[ \t]*<link href="https:\/\/fonts\.googleapis\.com\/css2[^>]*>\r?\n[ \t]*<link rel="stylesheet" href="styles\.css" \/>/,
      HEAD.join(NP)
    );
    if (s === before) throw new Error(`${page}: head block did not match`);
    await writeFile(page, s, 'utf8');
    console.log(`${page.padEnd(18)}head rewired`);
  }
}

/* ---- 5. the repainted hats ---------------------------------------------- */
let idx = await readFile('index.html', 'utf8');
if (idx.includes('./assets/hats.png')) {
  idx = idx.replaceAll('./assets/hats.png', './assets/hats-signal.png');
  await writeFile('index.html', idx, 'utf8');
  console.log('index.html        hats artwork swapped');
} else {
  console.log('index.html        hats already the Signal artwork');
}

console.log('\nPublished. styles.css is untouched — identity.css layers over it,');
console.log('so backing this out is removing five lines from four heads.');
