/* Puts the Signal identity on every page of the portfolio namespace.
 *
 * It DISCOVERS those pages rather than listing them. The first version carried a
 * hardcoded list of four and duly styled four, leaving about-me, gtd and the
 * three case studies on the old paper — a list is a claim about the site that
 * goes stale the moment anyone adds a page, and nothing checks it.
 *
 * A page belongs here if it says so itself: its namespace switcher marks
 * index.html as the current namespace. design-expert, nihongo and skillstone
 * each point at themselves and are left alone — they have their own identities,
 * and this paper does not belong on a dark character sheet.
 *
 * Idempotent. Run after changing explorations/parked/signal*.css, or after
 * explorations/download-display-fonts.mjs adds a family.
 *
 *   node publish-identity.mjs
 */
import { readFile, writeFile, readdir } from 'node:fs/promises';
import path from 'node:path';

const ROOT = process.cwd();
const nl = (s) => (s.includes('\r\n') ? '\r\n' : '\n');
const abs = (...p) => path.resolve(...p).replaceAll('\\', '/');

/* ---- 1. fonts and their stylesheets already live here -------------------- */
/* explorations/download-*.mjs write straight into fonts/, fonts.css and
   display-fonts.css at this root — there is nothing to copy. */

/* ---- 2. one identity stylesheet ----------------------------------------- */
/* signal-original.css only ever held #clients rules, scoped by that id and so
   inert everywhere else. Two files were a build-time convenience, not a
   boundary worth keeping. */
const shared = await readFile('explorations/parked/signal.css', 'utf8');
const home = await readFile('explorations/parked/signal-original.css', 'utf8');
const N = nl(shared);

const identity = [
  '/* Signal — the site identity.',
  '   Type, palette, the nav, the ink-inversion row, and the bar section on the',
  '   home page. Loads AFTER styles.css and overrides it; styles.css still owns',
  '   the layout. Generated by publish-identity.mjs from explorations/parked/ —',
  '   edit there and re-run. */',
  '',
  shared.replace(/^\/\*[\s\S]*?\*\/\r?\n/, '').trimStart(),
  '',
  home
    .replace(/^\/\*[\s\S]*?\*\/\r?\n/, '')
    .trimStart()
    /* Root-relative, not "./assets": this sheet is loaded from projects/ too,
       where a relative path would look for the art inside that folder. The rule
       is scoped to #clients so it never paints there, but a path that is only
       correct by accident is a trap for whoever edits it next. */
    .replaceAll('../assets/', '/assets/'),
].join(N);

await writeFile('identity.css', identity, 'utf8');
console.log(`identity.css      ${Math.round(identity.length / 1024)}KB`);

/* ---- 3. find the pages --------------------------------------------------- */
const candidates = [];
for (const dir of ['.', 'projects']) {
  for (const name of await readdir(path.join(ROOT, dir))) {
    if (name.endsWith('.html')) candidates.push(path.join(dir, name).replaceAll('\\', '/').replace(/^\.\//, ''));
  }
}

const pages = [];
const skipped = [];
for (const rel of candidates) {
  const s = await readFile(rel, 'utf8');
  if (!s.includes('<nav class="top"')) { skipped.push([rel, 'no shared nav']); continue; }
  const cur = s.match(/data-href="([^"]+)"[^>]*class="current"/);
  if (!cur) { skipped.push([rel, 'switcher declares no current namespace']); continue; }
  if (abs(ROOT, path.dirname(rel), cur[1]) !== abs(ROOT, 'index.html')) {
    skipped.push([rel, `another namespace (${cur[1]})`]);
    continue;
  }
  pages.push(rel);
}

console.log(`\nportfolio namespace — ${pages.length} pages`);

/* ---- 4. link it from every one of them ---------------------------------- */
let linked = 0;
for (const rel of pages) {
  let s = await readFile(rel, 'utf8');
  const NP = nl(s);
  const up = rel.includes('/') ? '../' : './';

  if (s.includes(`${up}identity.css`)) { console.log(`  ${rel.padEnd(24)} ok`); continue; }

  const head = [
    `<link rel="stylesheet" href="${up}fonts.css" />`,
    `<link rel="stylesheet" href="${up}display-fonts.css" />`,
    `<link rel="stylesheet" href="${up}styles.css" />`,
    `<link rel="stylesheet" href="${up}identity.css" />`,
    `<script src="${up}nav-current.js" defer></script>`,
  ].join(NP);

  const before = s;
  // Drop the Google Fonts CDN: every face is self-hosted now.
  s = s.replace(/[ \t]*<link rel="preconnect"[^>]*>\r?\n/g, '');
  s = s.replace(
    /[ \t]*<link href="https:\/\/fonts\.googleapis\.com\/css2[^>]*>\r?\n[ \t]*<link rel="stylesheet" href="(?:\.\/|\.\.\/)?styles\.css" \/>/,
    head
  );
  if (s === before) throw new Error(`${rel}: head block did not match — check its <link> order`);
  await writeFile(rel, s, 'utf8');
  linked += 1;
  console.log(`  ${rel.padEnd(24)} head rewired`);
}

/* ---- 5. the repainted hats (home page only) ------------------------------ */
let idx = await readFile('index.html', 'utf8');
if (idx.includes('./assets/hats.png')) {
  idx = idx.replaceAll('./assets/hats.png', './assets/hats-signal.png');
  await writeFile('index.html', idx, 'utf8');
  console.log('\nindex.html        hats artwork swapped');
}

if (skipped.length) {
  console.log('\nleft alone:');
  for (const [rel, why] of skipped) console.log(`  ${rel.padEnd(24)} ${why}`);
}
console.log(`\n${linked} newly linked. styles.css untouched — identity.css layers over it.`);
